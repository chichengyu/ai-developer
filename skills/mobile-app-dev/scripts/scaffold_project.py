SCAFFOLDS = {
    "flutter": FLUTTER,
    "react-native": REACT_NATIVE,
    "compose": COMPOSE,
    "swiftui": SWIFTUI,
    "maui": MAUI,
    "kmp": KMP,
    "capacitor": CAPACITOR,
    "tauri": TAURI,
}


def scaffold(framework: str, output_dir: Path, name: str) -> Path:
    key = framework.strip().lower()
    if key not in SCAFFOLDS:
        raise ValueError(f"Unsupported framework: {framework}")
    root = Path(output_dir)
    root.mkdir(parents=True, exist_ok=True)
    for rel, content in SCAFFOLDS[key].items():
        package_path = f"com/example/{_sanitize(name)}"
        target = root / (
            rel.replace("{Name}", _class_name(name))
            .replace("{name}", _sanitize(name))
            .replace("{package}", package_path)
        )
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(_render(content, name).encode("utf-8"))
    return root


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate a mobile project skeleton.")
    parser.add_argument("--framework", required=True, choices=sorted(SCAFFOLDS))
    parser.add_argument("--name", required=True, help="project/app name")
    parser.add_argument("--output-dir", default=".", help="output directory")
    args = parser.parse_args(argv)
    root = scaffold(args.framework, Path(args.output_dir), args.name)
    print(f"Scaffolded {args.framework} project in {root}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
