"""scaffold_project.py -- generate a minimal project skeleton.

Supports Flutter, React Native, Jetpack Compose, SwiftUI, .NET MAUI,
Kotlin Multiplatform, Capacitor, and Tauri Mobile. Generated files are
UTF-8 without BOM.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path


def _sanitize(name: str) -> str:
    return re.sub(r"[^a-zA-Z0-9]+", "_", name).strip("_").lower() or "app"


def _class_name(name: str) -> str:
    return "".join(part.capitalize() for part in _sanitize(name).split("_"))


def _render(content: str, name: str) -> str:
    package = _sanitize(name)
    return (
        content.replace("{Name}", _class_name(name))
        .replace("{name}", package)
        .replace("{package}", f"com.example.{package}")
    )


